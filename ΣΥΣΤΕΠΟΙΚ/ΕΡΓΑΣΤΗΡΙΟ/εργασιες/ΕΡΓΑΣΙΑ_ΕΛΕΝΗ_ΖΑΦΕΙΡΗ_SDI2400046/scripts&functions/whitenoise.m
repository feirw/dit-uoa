% =========================================================================
% 3.3 Θόρυβος (AM με προσθήκη AWGN) - Βελτιωμένη έκδοση
% =========================================================================


% =========================================================================
% Παράμετροι
% =========================================================================
fs = 50000;                 % Συχνότητα δειγματοληψίας (Hz)
T = 0.05;                   % Διάρκεια προσομοίωσης (s)
t = 0:1/fs:T-1/fs;          % Χρονικό διάνυσμα

f1 = 50;
f2 = 120;                   % Συχνότητες πληροφορίας (Hz)

fc = 1000;                  % Συχνότητα φέροντος (Hz)
Ac = 1;                     % Πλάτος φέροντος
mu = 0.7;                   % Δείκτης διαμόρφωσης

% =========================================================================
% Message Signal
% =========================================================================
m = cos(2*pi*f1*t) + 0.5*cos(2*pi*f2*t);

% =========================================================================
% Καθαρό AM σήμα
% =========================================================================
s_am = Ac * (1 + mu*m) .* cos(2*pi*fc*t);

% =========================================================================
% Τιμές θορύβου (τυπική απόκλιση)
% =========================================================================
sigma_values = [0.1 0.3 0.6];

% =========================================================================
% FFT Preparation
% =========================================================================
N = length(t);
f_axis = (-N/2:N/2-1)*(fs/N);

figure;

% =========================================================================
% Loop για διαφορετικά επίπεδα AWGN
% =========================================================================
for i = 1:length(sigma_values)

    sigma = sigma_values(i);

    % ---------------------------------------------------------------------
    % Gaussian White Noise
    % ---------------------------------------------------------------------
    noise = sigma * randn(size(t));

    % ---------------------------------------------------------------------
    % Θορυβώδες AM σήμα
    % ---------------------------------------------------------------------
    s_noisy = s_am + noise;

    % ---------------------------------------------------------------------
    % FFT
    % ---------------------------------------------------------------------
    S_noisy_fft = fftshift(fft(s_noisy));
    S_noisy_fft = abs(S_noisy_fft);
    S_noisy_fft = S_noisy_fft / max(S_noisy_fft);

    % =====================================================================
    % Time Domain
    % =====================================================================
    subplot(3,2,2*i-1);

    plot(t, s_noisy, 'b', 'LineWidth', 1);
    hold on;

    % Envelope
    env = Ac*(1 + mu*m);

    plot(t, env, 'r--', 'LineWidth', 1.2);
    plot(t, -env, 'r--', 'LineWidth', 1.2);



    xlabel('Χρόνος (s)');
    ylabel('Πλάτος');

    xlim([0 0.05]);
    grid on;

    % =====================================================================
    % Frequency Domain
    % =====================================================================
    subplot(3,2,2*i);

    plot(f_axis, S_noisy_fft, 'k', 'LineWidth', 1);



    xlabel('Συχνότητα (Hz)');
    ylabel('Norm. Ampl.');

    xlim([-2000 2000]);
    grid on;

end

% =========================================================================
% Γενικός τίτλος
% =========================================================================
sgtitle('AM Σήμα με Προσθήκη Gaussian Θορύβου (AWGN)');
