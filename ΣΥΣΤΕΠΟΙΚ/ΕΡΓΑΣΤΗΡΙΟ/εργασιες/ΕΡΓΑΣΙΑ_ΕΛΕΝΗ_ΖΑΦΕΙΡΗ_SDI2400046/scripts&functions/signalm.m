% =============================================================
% 3.1 Σήμα πληροφορίας και Φέρον σήμα
% =============================================================

% Ορισμός παραμέτρων προσομοίωσης (από τον Πίνακα 4 της εκφώνησης μας)
fs = 50000;          % Βασική συχνότητα προσομοίωσης σε Hz
T = 0.05;            % Διάρκεια προσομοίωσης σε sec
f1 = 50;             % Συχνότητα 1ου συνημιτόνου (Hz)
f2 = 120;            % Συχνότητα 2ου συνημιτόνου (Hz)
Ac = 1;              % Πλάτος φέροντος
fc = 1000;           % Συχνότητα φέροντος σε Hz

% Βήμα 1: Δημιουργία χρονικού διανύσματος t
t = 0:1/fs:T;

% Βήμα 2: Δημιουργία σήματος πληροφορίας m(t) = cos(2πf1t) + 0.5cos(2πf2t)
m = cos(2*pi*f1*t) + 0.5*cos(2*pi*f2*t);

% Βήμα 3: Δημιουργία φέροντος σήματος c(t) = Ac*cos(2πfct)
c = Ac * cos(2*pi*fc*t);

% Βήμα 4: Παραγωγή γραφημάτων με χρήση της subplot
figure;

% 1ο Γράφημα: Σήμα πληροφορίας
subplot(2, 1, 1);
plot(t, m);
title('Σήμα Πληροφορίας m(t) = cos(2\pi f_1 t) + 0.5 cos(2\pi f_2 t)');
xlabel('Χρόνος (s)');
ylabel('Πλάτος');
grid on;

% 2ο Γράφημα: Φέρον σήμα
subplot(2, 1, 2);
plot(t, c);
title('Φέρον Σήμα c(t) = A_c cos(2\pi f_c t)');
xlabel('Χρόνος (s)');
ylabel('Πλάτος');
grid on;

